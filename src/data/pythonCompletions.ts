export function getCompletionsForImports(imports: string[]): CompletionItem[] {
  const completions: CompletionItem[] = [];
  
  for (const imp of imports) {
    const libCompletions = STANDARD_LIBRARY_COMPLETIONS[imp];
    if (libCompletions) {
      completions.push(...libCompletions);
    }
  }
  
  return completions;
}
